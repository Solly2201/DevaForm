/**
 * Copy what the build script MEASURED into the TypeScript manifest.
 *
 * A mesh body's manifest entry carries numbers nobody typed: the surfaces,
 * the thumb axes, the fist's aperture, the torso sampled all the way
 * round. They are produced by build-human-base.mjs and consumed by the
 * engine, and until now the journey between those two points was a person
 * copying them. Copies drift — the committed bounds were two builds old —
 * and a drifted measurement is worse than no measurement, because
 * ornaments go on being fitted to a body that no longer exists.
 *
 * So the copy is mechanical, and a test holds the manifest to the built
 * asset afterwards. The region it rewrites is delimited in the manifest;
 * everything outside it stays hand-authored, because the rest of an asset
 * entry is editorial (names, descriptions, compatibility) and should be.
 *
 * Run from apps/web:  node scripts/sync-measured-manifest.mjs
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "../../..");

const TARGETS = [
  {
    asset: path.join(here, "../public/assets/foundations/bodies/human/1/asset.json"),
    manifest: path.join(repo, "packages/asset-system/src/manifests/shared.ts"),
    marker: "humanoid.body.human",
    fields: ["geometry", "morphTargets", "bodyProfile", "gripAxes", "gripShapes", "gripSeats", "faceAxes", "torsoSurface", "legEnvelope", "skullEnvelope", "poiseAxes", "poiseSeats"],
  },
  {
    asset: path.join(here, "../public/assets/foundations/bodies/human4/1/asset.json"),
    manifest: path.join(repo, "packages/asset-system/src/manifests/shared.ts"),
    marker: "humanoid.body.human4",
    fields: ["geometry", "morphTargets", "bodyProfile", "gripAxes", "gripShapes", "gripSeats", "faceAxes", "torsoSurface", "legEnvelope", "skullEnvelope", "poiseAxes", "poiseSeats"],
  },
];

/** Compact, deterministic TS literal — arrays of numbers stay on one line. */
function literal(value, indent) {
  const pad = "  ".repeat(indent);
  const inner = "  ".repeat(indent + 1);
  if (Array.isArray(value)) {
    if (value.every((v) => typeof v === "number")) return `[${value.join(", ")}]`;
    return `[\n${value.map((v) => inner + literal(v, indent + 1)).join(",\n")},\n${pad}]`;
  }
  if (value && typeof value === "object") {
    const entries = Object.entries(value);
    if (entries.length === 0) return "{}";
    return `{\n${entries
      .map(([key, v]) => `${inner}${/^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key)}: ${literal(v, indent + 1)}`)
      .join(",\n")},\n${pad}}`;
  }
  return JSON.stringify(value);
}

let changed = 0;
for (const target of TARGETS) {
  const built = JSON.parse(await readFile(target.asset, "utf8"));
  const source = await readFile(target.manifest, "utf8");
  const open = `// <measured ${target.marker}> generated by scripts/sync-measured-manifest.mjs`;
  const close = `// </measured ${target.marker}>`;
  const start = source.indexOf(open);
  const end = source.indexOf(close);
  if (start < 0 || end < 0) {
    console.error(`  MISSING markers for ${target.marker} in ${path.relative(repo, target.manifest)}`);
    process.exitCode = 1;
    continue;
  }
  const body = target.fields
    .filter((field) => built[field] !== undefined)
    .map((field) => `    ${field}: ${literal(built[field], 2)},`)
    .join("\n");
  const replaced =
    source.slice(0, start + open.length) + "\n" + body + "\n    " + source.slice(end);
  if (replaced !== source) {
    await writeFile(target.manifest, replaced);
    changed += 1;
  }
  console.log(`  ${changed ? "updated" : "unchanged"}  ${target.marker}`);
}
